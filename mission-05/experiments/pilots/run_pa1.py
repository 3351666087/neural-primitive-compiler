"""Pilot PA-1 (protocol section 9, amendment 1): contract composition vs same-prior search.

Per target (T1, T2, T3, M1..M4):
  A-P      ap.construct (local checks) + emit + compile at N = 7 -> construction CPU
  A-SAME   asame.construct on V_train (macro simulation, CEGIS) + emit + compile at N = 7 -> construction CPU
  A-FLAT   aflat.construct on V_train (decision lists from optimal plans, 600 s) + emit + compile at N = 7
  judges   J1-sym on V_train (N = 5, 6, 7) and V_unseen (N = 9, 12, 15) for every constructed controller;
           J1-net (network, lockstep) for A-P on 200 V_train + 50 per unseen size (seeded);
           J2 model checking for A-P: J1-sym on every instance with N = 6, K <= 4
  A-FSM    closed-form count of the explicit controller table (states of the V_train family at N = 5, 6, 7)
CPU = time.process_time. The runner is neutral: it imports both the judge and the library and passes plain data.

  python -I mission-05/experiments/pilots/run_pa1.py        # writes pa1.json (updated after every target)
"""

from __future__ import annotations

import json
import random
import sys
import time
from math import comb
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = HERE.parent
sys.path.insert(0, str(EXP / "judge"))
sys.path.insert(0, str(EXP / "lib"))
import cir_interp as CI  # noqa: E402
import instances as INS  # noqa: E402
import net_loop as NL  # noqa: E402
import aflat  # noqa: E402
import ap  # noqa: E402
import asame  # noqa: E402
import cirgen  # noqa: E402
import compile_cir as CC  # noqa: E402

OUT = HERE / "pa1.json"


def cpu():
    return time.process_time()


def judge_all(make_prog, spec, train, unseen):
    res = {}
    for N in (5, 6, 7):
        insts = [i for i in train if i["N"] == N]
        res[f"train_N{N}"] = CI.judge_set(make_prog(N), spec, insts)
    for N, insts in unseen.items():
        res[f"unseen_N{N}"] = CI.judge_set(make_prog(N), spec, insts)
    res["total_failures"] = sum(v["failures"] for v in res.values())
    return res


def net_check(plan, spec, train, unseen, seed=5):
    rng = random.Random(seed)
    groups = {"train": rng.sample(train, min(200, len(train)))}
    for N, insts in unseen.items():
        groups[f"unseen_N{N}"] = rng.sample(insts, 50)
    out = {}
    for gname, insts in groups.items():
        byN = {}
        for i in insts:
            byN.setdefault(i["N"], []).append(i)
        mism = fails = n = 0
        for N, grp in byN.items():
            prog = cirgen.emit(plan, spec, N)
            net, info = CC.compile_cir(prog)
            prog["D"] = info["D"]
            r = NL.run_net_lockstep(net, prog, spec, grp)
            mism += r["episodes_with_mismatch"]
            fails += sum(o != "SUCCESS" for o in r["outcomes"])
            n += len(grp)
        out[gname] = {"episodes": n, "mismatch_episodes": mism, "failures": fails}
    return out


def structure(make_prog):
    out = {}
    for N in (5, 6, 7, 9, 12, 15):
        prog = make_prog(N)
        net, info = CC.compile_cir(prog)
        out[N] = dict(info, cir_nodes=len(prog["nodes"]))
    return out


def fsm_states(spec, N, Kmax):
    P = len(INS.goal_colours(spec)) + 1
    tot = 0
    for K in range(1, Kmax + 1):
        tot += N * (comb(N, K) * P ** K + comb(N, K - 1) * P ** (K - 1) * P)
    return tot


def main():
    pool = json.loads((EXP / "judge" / "pool.json").read_text())
    out = json.loads(OUT.read_text()) if OUT.exists() else {"targets": {}}
    out["label"] = "PA-1 (DEV): ARC-free LINE world; all instances generated by judge/instances.py"
    for tid, spec in pool["PA1"].items():
        if tid in out["targets"]:
            continue
        t0 = time.perf_counter()
        train, unseen = INS.v_train(spec), INS.v_unseen(spec)
        rec = {"name": spec["name"], "V_train": len(train)}
        # ---------------- A-P
        c0 = cpu()
        r = ap.construct(spec)
        c1 = cpu()
        rec["A-P"] = {k: v for k, v in r.items() if k != "plan"}
        if r["status"] == "CONSTRUCTED":
            plan = [tuple(x) for x in r["plan"]]
            CC.compile_cir(cirgen.emit(plan, spec, 7))
            c2 = cpu()
            rec["A-P"].update(plan=plan, cpu_search=c1 - c0, cpu_compile=c2 - c1, cpu_total=c2 - c0,
                              global_verifications=0)
            mk = lambda N, p=plan: cirgen.emit(p, spec, N)
            rec["A-P"]["J1_sym"] = judge_all(mk, spec, train, unseen)
            rec["A-P"]["J1_net"] = net_check(plan, spec, train, unseen)
            mc6 = INS.v_mc6(spec)
            rec["A-P"]["J2_mc6"] = CI.judge_set(mk(6), spec, mc6)
            rec["A-P"]["structure"] = structure(mk)
        print(tid, "A-P", r["status"], flush=True)
        # ---------------- A-SAME
        c0 = cpu()
        s = asame.construct(spec, train)
        c1 = cpu()
        rec["A-SAME"] = {k: v for k, v in s.items() if k != "plan"}
        if s["status"] == "CONSTRUCTED":
            plan = [tuple(x) for x in s["plan"]]
            CC.compile_cir(cirgen.emit(plan, spec, 7))
            c2 = cpu()
            rec["A-SAME"].update(plan=plan, cpu_search=c1 - c0, cpu_compile=c2 - c1, cpu_total=c2 - c0)
            mk = lambda N, p=plan: cirgen.emit(p, spec, N)
            rec["A-SAME"]["J1_sym"] = judge_all(mk, spec, train, unseen)
        else:
            rec["A-SAME"].update(cpu_total=c1 - c0)
        print(tid, "A-SAME", s["status"], flush=True)
        # ---------------- A-FLAT
        c0 = cpu()
        f = aflat.construct(spec, train, budget_s=600.0)
        c1 = cpu()
        rec["A-FLAT"] = {k: v for k, v in f.items() if k != "rules"}
        if f["status"] == "CONSTRUCTED":
            rules = f["rules"]
            CC.compile_cir(cirgen.emit_flat(rules, spec, 7))
            c2 = cpu()
            rec["A-FLAT"].update(rules=[[list(map(list, c)), a] for c, a in rules], cpu_total=c2 - c0)
            mk = lambda N, rl=rules: cirgen.emit_flat(rl, spec, N)
            rec["A-FLAT"]["J1_sym"] = judge_all(mk, spec, train, unseen)
        else:
            rec["A-FLAT"].update(cpu_total=c1 - c0)
        print(tid, "A-FLAT", f["status"], flush=True)
        # ---------------- A-FSM
        rec["A-FSM_states"] = {N: fsm_states(spec, N, K) for N, K in ((5, 3), (6, 4), (7, 4))}
        rec["wall_s"] = round(time.perf_counter() - t0, 1)
        out["targets"][tid] = rec
        OUT.write_text(json.dumps(out, indent=1, default=str))
        print(tid, "done", rec["wall_s"], "s", flush=True)


if __name__ == "__main__":
    main()
