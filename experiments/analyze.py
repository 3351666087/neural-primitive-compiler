"""Mechanical checks of the pre-registered hypotheses against raw results.

  python experiments/analyze.py      # writes experiments/results/HYPOTHESES_CHECK.md
"""

from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RES = ROOT / "results"
TASKS = ["A1_delayed_coincidence", "A2_burst2of3", "A3_a_without_recent_b", "B1_count3_reset", "B2_remember_query",
         "B2r_remember_query_lat2", "B3_first_since_reset", "C1_toggle_sparse", "C2_parity_dense", "C3_latched_alarm"]
METHODS = ["classical", "cegis_if", "cegis_memoryless", "compose_dag", "compose_cyclic_k2", "compose_cyclic_k3",
           "enumerate", "cegis_same_template"]


def nets(row):
    """Yield (label, entry) for every network produced for a task."""
    if "result" in row.get("classical", {}):
        yield "classical", row["classical"]["result"]
    for k, v in row.get("direct", {}).items():
        yield f"direct:{k}", v
    for m in METHODS[1:]:
        if m in row and "result" in row[m]:
            yield m, row[m]["result"]


def features(netd):
    ns = netd["neurons"]
    full = {n["name"]: max(n["vmax"], -n["vmin"]) for n in ns}
    partial_leak = [n["name"] for n in ns if 0 < n["leak"] < full[n["name"]]]
    integ = [n["name"] for n in ns if n["leak"] == 0]
    names = {n["name"] for n in ns}
    rec = [s for s in netd["synapses"] if s["src"] in names]
    self_loops = [s for s in rec if s["src"] == s["dst"]]
    return {"partial_leak": partial_leak, "perfect_integrators": integ, "recurrent_synapses": len(rec),
            "self_loops": len(self_loops), "bias_neurons": [n["name"] for n in ns if n["bias"] != 0]}


def main():
    rows = {}
    for t in TASKS:
        p = RES / f"{t}.json"
        if p.exists():
            rows[t] = json.loads(p.read_text())
    out = ["# Hypothesis checks (mechanical)", "", "Generated by `python experiments/analyze.py`.", ""]

    # H1/H2: decision procedure vs search
    out += ["## H1/H2: realisability decision vs search", "", "| task | classical | any search SOLVED | consistent |", "|---|---|---|---|"]
    for t, r in rows.items():
        cl = r["classical"]["info"].get("status")
        solved = [m for m in METHODS[1:] if m in r and r[m].get("status") in ("SOLVED", "SOLVED_BOUNDED")]
        ok = not (cl == "UNREALIZABLE" and solved)
        verified = all(e["verification"]["reach"]["status"] == "VERIFIED_UNBOUNDED" for _, e in nets(r))
        out.append(f"| {t} | {cl} | {', '.join(solved) or '—'} | {'yes' if ok and verified else 'NO'} |")

    # H3: succinctness and information bounds
    out += ["", "## H3: neurons vs state bits", "",
            "| task | min FSM states Q | ceil log2 Q | network | neurons | state_bits (upper) | effective bits | eff ≥ log2 Q | upper ≤ 4·ceil(log2 Q) |",
            "|---|---|---|---|---|---|---|---|---|"]
    h3b_ok, h3c_viol, ratios = True, [], []
    for t, r in rows.items():
        Q = r["fsm"].get("minimal_states")
        if not Q:
            continue
        lq = math.ceil(math.log2(Q)) if Q > 1 else 0
        cl_n = r["classical"]["result"]["stats"]["neurons"] if "result" in r["classical"] else None
        if "result" in r.get("cegis_if", {}) and cl_n:
            ratios.append((t, r["cegis_if"]["result"]["stats"]["neurons"], cl_n))
        for lab, e in nets(r):
            eb = e["effective_state_bits"]
            ub = e["stats"]["state_bits"]
            c1 = eb is not None and eb + 1e-9 >= math.log2(Q)
            c2 = ub <= 4 * max(1, lq)
            h3b_ok &= c1
            if not c2:
                h3c_viol.append((t, lab, ub, lq))
            out.append(f"| {t} | {Q} | {lq} | {lab} | {e['stats']['neurons']} | {ub} | {eb} | {'yes' if c1 else 'NO'} | {'yes' if c2 else 'no'} |")
    out += ["", f"- H3(b) effective bits ≥ log2 Q for every network: **{'holds' if h3b_ok else 'VIOLATED'}**",
            f"- H3(c) upper-bound state bits ≤ 4·ceil(log2 Q): violated by {len(h3c_viol)} networks: {h3c_viol}",
            "- H3(a) neurons CEGIS(IF) / classical: " + ", ".join(f"{t}: {a}/{b} = {a / b:.2f}" for t, a, b in ratios)]

    # Q2 control: IF vs memoryless
    out += ["", "## Q2: integrate-and-fire vs memoryless-only (CEGIS neuron search)", "",
            "| task | IF: smallest n solved | memoryless: trail |", "|---|---|---|"]
    for t, r in rows.items():
        def first(tr):
            for x in tr:
                if x["status"] in ("SOLVED", "SOLVED_BOUNDED"):
                    return x["n"]
            return None
        a = first(r["cegis_if"]["neuron_search"])
        b = ", ".join(f"n={x['n']}:{x['status']}" for x in r["cegis_memoryless"]["neuron_search"])
        out.append(f"| {t} | {a} | {b} |")

    # H5: who failed
    out += ["", "## H5: failures and timeouts per method", "", "| task | method | status | time s | candidates |", "|---|---|---|---|---|"]
    for t, r in rows.items():
        for m in METHODS[1:]:
            if m in r and r[m].get("status") not in ("SOLVED", "SOLVED_BOUNDED"):
                out.append(f"| {t} | {m} | {r[m]['status']} | {r[m]['total_time_s']} | {r[m].get('candidates')} |")

    # H6: features in CEGIS results
    out += ["", "## H6: structural features of CEGIS (IF) networks", "", "| task | neurons | features |", "|---|---|---|"]
    for t, r in rows.items():
        e = r["cegis_if"].get("result")
        if e:
            out.append(f"| {t} | {e['stats']['neurons']} | {json.dumps(features(e['network']))} |")
    (RES / "HYPOTHESES_CHECK.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
