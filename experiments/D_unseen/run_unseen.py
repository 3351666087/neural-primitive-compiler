"""Group D: unseen tasks fixed only after the compiler source is frozen. See PROTOCOL.md.

  python experiments/D_unseen/run_unseen.py freeze     # write freeze-manifest.json
  python experiments/D_unseen/run_unseen.py generate   # write tasks.npc from the seed in the manifest
  python experiments/D_unseen/run_unseen.py run        # run all methods, write results.json + SUMMARY.md
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
SRC = REPO / "src" / "npc"
sys.path.insert(0, str(REPO / "src"))

from npc.dsl import flatten, load_with_stdlib  # noqa: E402
from npc.fsm import NotCausal, classical_network, machine_from_spec, minimize  # noqa: E402
from npc.gen import random_formula  # noqa: E402
from npc.spec import show  # noqa: E402
from npc.synth import compose_dag, search_neurons, sketch  # noqa: E402
from npc.verify import verify_all  # noqa: E402

MANIFEST = HERE / "freeze-manifest.json"
TASKS = HERE / "tasks.npc"


def tree_hash() -> tuple[str, dict[str, str]]:
    files = {}
    for p in sorted(SRC.rglob("*")):
        if p.is_file() and "__pycache__" not in p.parts:
            files[str(p.relative_to(REPO))] = hashlib.sha256(p.read_bytes()).hexdigest()
    lines = "".join(f"{k} {v}\n" for k, v in files.items())
    return hashlib.sha256(lines.encode()).hexdigest(), files


def check_frozen() -> dict:
    if not MANIFEST.exists():
        sys.exit("no freeze manifest: run `freeze` first")
    man = json.loads(MANIFEST.read_text())
    h, _ = tree_hash()
    if h != man["tree_sha256"]:
        sys.exit(f"src/npc changed since the freeze ({h} != {man['tree_sha256']}); refusing to run")
    return man


def cmd_freeze(_):
    if MANIFEST.exists():
        sys.exit("manifest already exists; a re-freeze must be recorded by hand in PROTOCOL.md")
    h, files = tree_hash()
    MANIFEST.write_text(json.dumps({"tree_sha256": h, "frozen_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
                                    "files": files}, indent=2))
    print("frozen", h)


def cmd_generate(_):
    man = check_frozen()
    seed = int(man["tree_sha256"][:16], 16)
    rng = random.Random(seed)
    out = [f"# Generated by run_unseen.py generate from seed {seed} (tree {man['tree_sha256']}).", ""]
    for i in range(20):
        d = rng.choice([2, 2, 3])
        phi = random_formula(rng, ["a", "b"], depth=d)
        L = rng.choice([1, 2])
        g = f"y <-> prev[{L}]({show(phi)})" if L > 1 else f"y <-> prev({show(phi)})"
        out += [f"spec D{i:02d} {{", "  inputs a, b", "  outputs y", f"  guarantee {g}", "}", ""]
    TASKS.write_text("\n".join(out))
    print(TASKS.read_text())


def _entry(net, sp):
    res = verify_all(net, sp, T=8, timeout_s=120)
    return {"stats": net.stats(), "verification": {r.engine: r.status.value for r in res},
            "effective_state_bits": res[-1].stats.get("effective_state_bits"), "network": net.to_dict()}


def cmd_run(args):
    man = check_frozen()
    files = [TASKS] + ([HERE / "hand.npc"] if (HERE / "hand.npc").exists() else [])
    lib = load_with_stdlib(*files)
    sketches = load_with_stdlib(*files, *sorted((REPO / "experiments" / "llm_sketches").glob("D*.npc")))
    rows = []
    for name, sp in lib.specs.items():
        if args.only and name not in args.only:
            continue
        print(f"=== {name}: {show(sp.guarantee)}", flush=True)
        row = {"task": name, "guarantee": show(sp.guarantee)}
        try:
            M = minimize(machine_from_spec(sp))
            row["fsm_states"] = M.n
        except NotCausal:
            row["fsm_states"] = None
        except Exception as e:  # noqa: BLE001
            row["fsm_states"] = f"error {e}"
        t0 = time.perf_counter()
        net, info = classical_network(sp)
        row["classical"] = {"status": info.get("status"), "time_s": round(time.perf_counter() - t0, 3)}
        if net is not None:
            row["classical"].update(_entry(net, sp))
        r, trail = search_neurons(sp, n_max=3, T=8, timeout_s=args.budget)
        row["cegis"] = {"status": r.status, "trail": trail, "time_s": round(r.total_time_s, 3),
                        "iterations": r.iterations}
        if r.network is not None:
            row["cegis"].update(_entry(r.network, sp))
        c = compose_dag(lib, sp, T=8, max_size=3, timeout_s=args.budget / 2)
        row["compose_dag"] = {"status": c.status, "expr": c.detail.get("expr"), "time_s": round(c.total_time_s, 3),
                              "candidates": c.candidates}
        if c.network is not None:
            row["compose_dag"].update(_entry(c.network, sp))
        sk = [n for n in sketches.networks if n.startswith(name + "_")]
        row["llm_sketches"] = {}
        for n in sk:
            s = sketch(sketches, sketches.networks[n], sp, T=8, timeout_s=args.budget)
            row["llm_sketches"][n] = {"status": s.status, "candidates": s.candidates, "iterations": s.iterations,
                                      "time_s": round(s.total_time_s, 3), "assignment": s.detail.get("assignment"),
                                      "attempts": s.detail.get("attempts")}
            if s.network is not None:
                row["llm_sketches"][n].update(_entry(s.network, sp))
        print(json.dumps({k: (v if k in ("task", "fsm_states") else v.get("status") if isinstance(v, dict) and "status" in v else v)
                          for k, v in row.items() if k != "llm_sketches"}), flush=True)
        for n, v in row["llm_sketches"].items():
            print(f"   sketch {n}: {v['status']}", flush=True)
        rows.append(row)
    (HERE / "results.json").write_text(json.dumps({"manifest": man["tree_sha256"], "rows": rows}, indent=2, default=str))
    summarize(rows)


def summarize(rows):
    lines = ["# Group D results", "", "| task | guarantee | FSM states | classical | CEGIS | compose_dag | LLM sketch |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        def c(e):
            if e.get("network"):
                s = e["stats"]
                return f"{e['status']} {s['neurons']}n/{s['synapses']}s ({e.get('time_s', '?')}s)"
            return f"{e['status']} ({e.get('time_s', '?')}s)"
        sk = "; ".join(f"{k}: {v['status']}" for k, v in r["llm_sketches"].items()) or "—"
        g = r["guarantee"].replace("|", "\\|")
        lines.append(f"| {r['task']} | `{g}` | {r['fsm_states']} | {c(r['classical'])} | {c(r['cegis'])} | {c(r['compose_dag'])} | {sk} |")
    (HERE / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["freeze", "generate", "run"])
    ap.add_argument("--budget", type=float, default=120.0)
    ap.add_argument("--only", nargs="*")
    args = ap.parse_args()
    {"freeze": cmd_freeze, "generate": cmd_generate, "run": cmd_run}[args.cmd](args)


if __name__ == "__main__":
    main()
